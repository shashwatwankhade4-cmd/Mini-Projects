# Storing personal information in variables

full_name = "Shashwat Wankhade"      # String: stores complete name
age = 18                    # Integer: stores age in whole numbers
height_meters = 1.83          # Float: stores height with decimal value
is_student = True             # Boolean: stores True/False value

# Printing variables
print("Name:", full_name)
print("Age:", age)
print("Height:", height_meters)
print("Student:", is_student)

# Checking data types
print(type(full_name))
print(type(age))
print(type(height_meters))
print(type(is_student))