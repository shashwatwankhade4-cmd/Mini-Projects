# range(stop)
print("0 to 10:")
for i in range(11):
    print(i, end=" ")

print("\n")

# range(start, stop)
print("5 to 15:")
for i in range(5, 16):
    print(i, end=" ")

print("\n")

# range(start, stop, step)
print("Odd numbers from 1 to 21:")
for i in range(1, 22, 2):
    print(i, end=" ")

# Forms:
# range(stop)
# range(start, stop)
# range(start, stop, step)