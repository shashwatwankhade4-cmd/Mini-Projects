marks = [45, 78, 65, 90, 34, 82, 71]

# Ascending order
marks.sort()
print("Ascending:", marks)

# Descending order
marks.sort(reverse=True)
print("Descending:", marks)

# Reverse original list
original_marks = [45, 78, 65, 90, 34, 82, 71]
original_marks.reverse()
print("Reversed Original List:", original_marks)

# sort() arranges elements in order
# reverse() only reverses current order